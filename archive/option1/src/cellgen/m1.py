"""Option 1 Milestone 1 evidence (handout Table 7, M1): frame check, inv_1 and nand2_1 regenerated
and verified, the request reader and the network check. Writes results/option1/m1/."""
import csv
import json
import sys
from pathlib import Path

from dd2 import boolfn as bf
from dd2 import paths, provenance

from . import flow, network, request

# Option 1 handout Table 6 (test cells) and section 4.1 (reference cells).
TEST_FUNCTIONS = [
    ("!(A & B)", "nand2_1"), ("!(A | B)", "nor2_1"), ("!(A & B & C)", "nand3_1"), ("!(A | B | C)", "nor3_1"),
    ("!((A & B) | C)", "a21oi_1"), ("!((A | B) & C)", "o21ai_1"), ("!((A & B) | (C & D))", "a22oi_1"),
    ("!((A | B) & (C | D))", "o22ai_1"), ("A & B", "and2_1"), ("(A & B) | C", "a21o_1"),
    ("(A & !C) | (B & C)", "mux2_1"), ("(A & B) | (C & (A | B))", "maj3_1"), ("A ^ B", "xor2_1"),
    ("!(A & (B | (C & D)))", None), ("!(A | (B & (C | D)))", None), ("!((C&D) | (A&B&(C|D)))", None),
    ("(C&D) | (A&B&(C|D))", None),
]


def inputs_of(expr):
    return sorted({t for t in bf.tokenize(expr) if t[0].isalpha()})


def network_table() -> list:
    """The network check on every test function: one stage where Y allows it."""
    rows = []
    for expr, hd in TEST_FUNCTIONS:
        ins = inputs_of(expr)
        tt = bf.eval_expr(expr, ins)
        row = {"expression": expr, "inputs": " ".join(ins), "truth_table": bf.to_hex(tt, len(ins)), "hd_cell": hd or ""}
        try:
            net = network.single_stage(tt, ins)
            errs = network.switch_check(net, tt)
            row |= {"stages": 1, "transistors": len(net.transistors), "max_series": network.max_series(net),
                    "switch_check": "pass" if not errs else "fail: " + errs[0]}
        except ValueError as e:
            row |= {"stages": "multi (cp2)", "transistors": "", "max_series": "", "switch_check": f"not single-stage: {e}"}
        rows.append(row)
    return rows


def request_cases(work: Path) -> list:
    """The request reader on the Appendix A example and on requests it must refuse."""
    ex = json.loads((paths.ROOT / "docs/interface/request_example.json").read_text())
    cases = {"appendix_a_example": ex,
             "truth_table_mismatch": ex | {"truth_table": "0x077E"},
             "five_inputs": ex | {"inputs": list("ABCDE"), "expression": "A&B&C&D&E", "truth_table": "0x80000000"},
             "unknown_operator": ex | {"expression": "!((C $ D) | (A & B))"}}
    out = []
    for name, data in cases.items():
        r = request.parse(data)
        out.append({"case": name, "status": r.status, "reason": r.reason,
                    "truth_table": bf.to_hex(r.tt, len(r.inputs)) if r.status == "ok" else None})
    return out


def run(out: Path) -> int:
    out.mkdir(parents=True, exist_ok=True)
    from dd2 import envcheck
    import gdsfactory
    import klayout.db as kdb
    tools = {"course_image": envcheck.course_image(), "gdsfactory": gdsfactory.__version__,
             "klayout": getattr(kdb, "__version__", None) or kdb.Application.version() if hasattr(kdb, "Application") else None}
    try:
        from importlib.metadata import version
        tools["klayout"] = version("klayout")
    except Exception:
        pass
    rec = provenance.RunRecord(argv=["cellgen", "m1"], tools=tools)
    frame = flow.frame_report()
    provenance.write_json(out / "frame_check.json", frame)
    cells = {c: flow.build_reference(c) for c in ("inv_1", "nand2_1")}
    for c, rep in cells.items():
        rep["run"]["tools"] = tools
        provenance.write_json(out / f"{c}.json", rep)
    nets = network_table()
    with open(out / "network_check.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(nets[0]))
        w.writeheader()
        w.writerows(nets)
    reqs = request_cases(out)
    provenance.write_json(out / "request_reader.json", reqs)
    ok_req = [r["status"] for r in reqs] == ["ok", "fail", "unsupported", "fail"]
    ok_net = all(r["switch_check"] == "pass" for r in nets if r["stages"] == 1)
    ok = all(v["match"] for v in frame.values()) and all(r["status"] == "pass" for r in cells.values()) and ok_req and ok_net
    rec.finish(0 if ok else 1)
    summary = {"frame_matches_installed": {k: v["match"] for k, v in frame.items()},
               "cells": {c: {"status": r["status"], "failed": r["failed_checks"],
                             "width_sites": r["layout"]["width_sites"],
                             "checks": {k: v.get("status") for k, v in r["checks"].items()}} for c, r in cells.items()},
               "request_reader": "pass" if ok_req else "fail",
               "network_check": {"single_stage_functions": sum(r["stages"] == 1 for r in nets),
                                 "all_pass": ok_net},
               "tools": tools, "run": rec.asdict()}
    provenance.write_json(out / "summary.json", summary)
    lines = ["# Option 1 Milestone 1 evidence (generated by `make o1-m1`; do not edit)", "",
             "| cp1 requirement | Evidence | Status |", "|---|---|---|",
             f"| HD frame checked against installed inv_1 and nand2_1 | `results/option1/m1/frame_check.json` | "
             f"{'pass' if all(v['match'] for v in frame.values()) else 'FAIL'} |"]
    for c, r in cells.items():
        ck = r["checks"]
        lines.append(f"| {c} regenerated at 2.72 um ({r['layout']['width_sites']} sites): DRC {ck['drc']['errors']} in a "
                     f"tap row, LVS {ck['lvs']['result']} (vs installed: {ck['lvs_vs_installed']['result']}), "
                     f"abutment {ck['abutment']['errors']} errors in 4 fixtures, layers {ck['layers']['status']}, "
                     f"SPICE {ck['spice']['status']}, model {ck['model']['status']} | `results/option1/m1/{c}.json`, "
                     f"`cells/dd2_ref__{c}/` | {r['status']} |")
    lines.append(f"| Request reader (accept example; refuse mismatch, 5 inputs, bad operator) | "
                 f"`results/option1/m1/request_reader.json` | {'pass' if ok_req else 'FAIL'} |")
    lines.append(f"| Network check on the {summary['network_check']['single_stage_functions']} single-stage test "
                 f"functions | `results/option1/m1/network_check.csv` | {'pass' if ok_net else 'FAIL'} |")
    (out / "summary.md").write_text("\n".join(lines) + "\n")
    readme = paths.ROOT / "README.md"
    a, b = "<!-- o1-summary:start -->", "<!-- o1-summary:end -->"
    t = readme.read_text()
    if a in t and b in t:
        readme.write_text(t[:t.index(a) + len(a)] + "\n" + "\n".join(lines[2:]) + "\n" + t[t.index(b):])
    print("\n".join(lines))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(run(paths.results("option1", "m1")))
